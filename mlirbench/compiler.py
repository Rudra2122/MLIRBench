_HOST_KEY = "|".join(str(v) for k, v in sorted(host_info().items())
                     if k in ("machine", "system", "cpu_model"))

BASE_FLAGS = ["--iree-hal-target-device=local",
              "--iree-hal-local-target-device-backends=llvm-cpu"]
HOST = ["--iree-llvmcpu-target-cpu=host"]
NO_DT = ["--iree-opt-data-tiling=false"]


@dataclass
class Variant:
    name: str
    title: str
    what: str
    flags: list[str]
    tile: Optional[Callable[[Shape], TileConfig]] = None
    needs_tuning: bool = False
    tags: list[str] = field(default_factory=list)


def _scalar_tiled(s: Shape) -> TileConfig:
    return TileConfig(min(64, s.M), min(64, s.N), 0, 0, 0, pipeline="CPUDefault")


