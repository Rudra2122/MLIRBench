@dataclass
class CompileResult:
    ok: bool
    vmfb: Optional[Path]
    dump_dir: Optional[Path]
    seconds: float
    vmfb_bytes: int = 0
    error: str = ""
    flags: list[str] = field(default_factory=list)
    mlir_path: Optional[Path] = None

    def to_dict(self) -> dict:
        return {"ok": self.ok, "vmfb": str(self.vmfb) if self.vmfb else None,
                "dump_dir": str(self.dump_dir) if self.dump_dir else None,
                "compile_seconds": round(self.seconds, 3), "vmfb_bytes": self.vmfb_bytes,
                "error": self.error[-1500:], "flags": self.flags}


def compile_kernel(shape: Shape, flags: list[str], tile: Optional[TileConfig] = None,
                   tag: str = "", dump: bool = True, extra: Optional[list[str]] = None,
                   out_root: Path = BUILD) -> CompileResult:
    mlir = matmul_mlir(shape, tile)
    all_flags = BASE_FLAGS + flags + (extra or [])
    # host is part of the key: "--iree-llvmcpu-target-cpu=host" means different
    # code on different machines, so a copied build/ must never be reused
    key = hashlib.sha1((mlir + " ".join(all_flags) + _HOST_KEY).encode()).hexdigest()[:10]
    out = out_root / shape.name / f"{tag or 'k'}_{key}"
    out.mkdir(parents=True, exist_ok=True)
    src, vmfb, dump_dir = out / "kernel.mlir", out / "kernel.vmfb", out / "dispatches"
    src.write_text(mlir)
    if vmfb.exists() and (not dump or dump_dir.exists()):
        return CompileResult(True, vmfb, dump_dir if dump else None, 0.0,
                             vmfb.stat().st_size, flags=all_flags, mlir_path=src)
    cmd = [find_tool("iree-compile"), str(src), *all_flags, "-o", str(vmfb)]
    if dump:
        cmd.append(f"--iree-hal-dump-executable-files-to={dump_dir}")
    t0 = time.perf_counter()
    proc = run(cmd, timeout=900)
    dt = time.perf_counter() - t0
    if proc.returncode != 0 or not vmfb.exists():
        err = "\n".join(l for l in proc.stderr.splitlines() if "error" in l.lower())[:1500]
        return CompileResult(False, None, None, dt, error=err or proc.stderr[-1500:],
                             flags=all_flags, mlir_path=src)
    return CompileResult(True, vmfb, dump_dir if dump else None, dt, vmfb.stat().st_size,
                         flags=all_flags, mlir_path=src)


def compile_variant(shape: Shape, variant: Variant, tile: Optional[TileConfig] = None,
                    **kw) -> CompileResult:
    if tile is None and variant.tile is not None:
        tile = variant.tile(shape)
    return compile_kernel(shape, variant.flags, tile=tile, tag=variant.name, **kw)


def compile_to_phase(src: Path, flags: list[str], phase: str, out: Path) -> tuple[bool, str]:
    proc = run([find_tool("iree-compile"), str(src), *BASE_FLAGS, *flags,
                f"--compile-to={phase}", "-o", str(out)], timeout=900)
    return proc.returncode == 0, proc.stderr[-2000:]
